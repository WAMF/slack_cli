// Copies the shared RichMessage schema and golden files from a checkout of
// WAMF/WAAF_DigitalWorkforce into this repository.
//
// Usage:
//   dart run tool/sync_rich_message.dart <path-to-WAAF_DigitalWorkforce>
//
// The schema in that repository is the single source of truth
// (backend/convex/convex/rich_message/rich_message_schema.json). This script
// writes it into lib/src/rich_message/rich_message_schema.g.dart, so the
// compiled CLI carries it, and copies the schema and the golden files into
// test/fixtures/rich_message/. The tests then prove that this CLI gives the
// same output as the backend renderer for the same input.
import 'dart:io';

const _schemaPath =
    'backend/convex/convex/rich_message/rich_message_schema.json';
const _fixturesPath = 'test_fixtures/rich_message';
const _generatedPath = 'lib/src/rich_message/rich_message_schema.g.dart';
const _localFixtures = 'test/fixtures/rich_message';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'Usage: dart run tool/sync_rich_message.dart <WAAF_DigitalWorkforce>',
    );
    exitCode = 64;
    return;
  }
  final source = args.single;
  final commit = Process.runSync('git', [
    '-C',
    source,
    'rev-parse',
    'HEAD',
  ]).stdout.toString().trim();

  final schema = File('$source/$_schemaPath').readAsStringSync();
  if (schema.contains("'''")) {
    stderr.writeln('The schema contains three single quotes; cannot embed.');
    exitCode = 65;
    return;
  }
  File(_generatedPath).writeAsStringSync(
    '// Generated by tool/sync_rich_message.dart. Do not modify.\n'
    '// Source: WAMF/WAAF_DigitalWorkforce@$commit\n'
    '//   $_schemaPath\n'
    '// ignore_for_file: lines_longer_than_80_chars\n'
    '\n'
    '/// The shared RichMessage JSON Schema, byte for byte.\n'
    "const String richMessageSchemaJson = r'''\n$schema''';\n",
  );

  final target = Directory(_localFixtures)..createSync(recursive: true);
  File('$_localFixtures/rich_message_schema.json').writeAsStringSync(schema);
  for (final entity in Directory('$source/$_fixturesPath').listSync()) {
    if (entity is! File || !entity.path.endsWith('.json')) continue;
    final name = entity.uri.pathSegments.last;
    entity.copySync('${target.path}/$name');
  }
  File('$_localFixtures/SOURCE')
      .writeAsStringSync('WAMF/WAAF_DigitalWorkforce@$commit\n');
  stdout.writeln('Synced the RichMessage schema and goldens from $commit.');
}
